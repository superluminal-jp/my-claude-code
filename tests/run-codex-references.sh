#!/usr/bin/env bash
# Reference-integrity suite for the removal of the hand-maintained Codex port
# (feature 021). Replaces run-codex-sync.sh: since Codex configuration is now
# generated locally and git-ignored, there is no stable artifact to diff, so
# this suite verifies instead that the repository is internally consistent
# after the removal — no dangling paths, a flat root AGENTS.md, generated
# paths ignored, and only official documentation hosts cited.
#
# Contract: specs/021-codex-official-import/contracts/removal-manifest.md
# (RULE-01 … RULE-10, including the .agents/skills/<name> carve-out).
#
# Deterministic: no network, no dependency on ~/.codex or ~/.agents.
#
# Usage: bash tests/run-codex-references.sh

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="${CODEX_REFS_REPO_ROOT_OVERRIDE:-$REPO_ROOT}"

GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[0;33m'
NC='\033[0m'

PASS=0
FAIL=0
SKIP=0
FAIL_NAMES=""

if ! command -v jq >/dev/null 2>&1; then
  echo "Error: 'jq' is required for this test." >&2
  exit 1
fi

check() {
  local name="$1" cond="$2"
  if [ "$cond" = "0" ]; then
    PASS=$((PASS + 1))
    printf "${GREEN}PASS${NC} %s\n" "$name"
  else
    FAIL=$((FAIL + 1))
    FAIL_NAMES="$FAIL_NAMES\n  - $name"
    printf "${RED}FAIL${NC} %s\n" "$name"
  fi
}

skip() {
  local name="$1" reason="$2"
  SKIP=$((SKIP + 1))
  printf "${YELLOW}SKIP${NC} %s (%s)\n" "$name" "$reason"
}

cd "$REPO_ROOT" || exit 1

# Files searched for dangling references. specs/** and docs/adr/** are exempt
# by design: they are historical records and must keep naming what existed.
LIVE_FILES="README.md README.ja.md AGENTS.md CLAUDE.md install.sh .gitignore"
# `.claude/**` is deliberately absent: NFR-002 forbids editing it in this
# change, and the references it still carries (a permission allowlist entry and
# two comments naming the retired adapters) are inert without those paths.
# Cleaning them up is follow-up work, tracked in the feature's spec.
LIVE_DIRS="scripts tests"

live_grep() {
  # Prints "path:line:text" for every match of $1 across the live surfaces.
  local pattern="$1" f
  for f in $LIVE_FILES; do
    [ -f "$f" ] && grep -nE "$pattern" "$f" 2>/dev/null | sed "s|^|$f:|"
  done
  for f in $LIVE_DIRS; do
    [ -d "$f" ] && grep -rnE "$pattern" "$f" 2>/dev/null
  done
  return 0
}

# --- RULE-01: no reference to a deleted path -------------------------------
# `.agents/skills/<name>` is deliberately excluded: those paths are deleted as
# tracked symlinks but reappear as generated skills after `/import`, and
# AGENTS.md must keep pointing at them.
# Only paths that never come back count. `.codex/hooks/`, `.codex/hooks.json`,
# `.codex/config.toml` and `.codex/agents/` are regenerated by `/import`, so
# naming them is correct, not dangling. `~/`-prefixed matches are instructions
# for cleaning the user's home directory and are likewise legitimate.
DELETED_REFS='\.codex/(AGENTS\.md|README\.md|rules/|prompts/)|\.codex/hooks/[a-z-]+-adapter\.sh|tests/run-codex-sync(-drift)?\.sh'
# Shell comments are exempt for the same reason RULE-10 exempts them: a comment
# explaining *why* a path was removed necessarily names it, and forbidding that
# would push the repository toward unexplained deletions. Markdown is not
# exempt — `#` there is a heading, not a comment.
# shellcheck disable=SC2088  # literal text match on documentation, not a path
hits="$(live_grep "$DELETED_REFS" | grep -v '~/\.codex' | grep -vE '\.sh:[0-9]+:[[:space:]]*#')"
if [ -n "$hits" ]; then
  printf "%s\n" "$hits" | sed 's/^/    /'
fi
check "RULE-01: no live file references a deleted path" "$([ -z "$hits" ] && echo 0 || echo 1)"

# --- RULE-02: no surviving SYNC-nn token -----------------------------------
sync_hits="$(live_grep 'SYNC-[0-9][0-9]')"
if [ -n "$sync_hits" ]; then
  printf "%s\n" "$sync_hits" | sed 's/^/    /'
fi
check "RULE-02: no SYNC-nn check id survives" "$([ -z "$sync_hits" ] && echo 0 || echo 1)"

# --- RULE-03: root AGENTS.md is a regular file, not a symlink --------------
check "RULE-03: root AGENTS.md is a regular file, not a symlink" \
  "$([ -f AGENTS.md ] && [ ! -L AGENTS.md ] && echo 0 || echo 1)"

# --- RULE-04: root AGENTS.md is within Codex's instruction budget ----------
if [ -f AGENTS.md ] && [ ! -L AGENTS.md ]; then
  agents_bytes="$(wc -c <AGENTS.md | tr -d ' ')"
  check "RULE-04: root AGENTS.md is >1KiB and <=32KiB (is ${agents_bytes}B)" \
    "$([ "$agents_bytes" -gt 1024 ] && [ "$agents_bytes" -le 32768 ] && echo 0 || echo 1)"
else
  skip "RULE-04: root AGENTS.md size" "AGENTS.md missing or is a symlink — see RULE-03"
fi

# --- RULE-05: root AGENTS.md contains no @-import lines --------------------
# Codex composes instructions by directory-walk concatenation only; it does not
# expand `@path` imports (openai/codex issue #17401, open). A leading `@` line
# would therefore deliver nothing.
if [ -f AGENTS.md ] && [ ! -L AGENTS.md ]; then
  at_lines="$(grep -n '^@' AGENTS.md 2>/dev/null)"
  [ -n "$at_lines" ] && printf "%s\n" "$at_lines" | sed 's/^/    /'
  check "RULE-05: root AGENTS.md has no unexpandable @-import line" \
    "$([ -z "$at_lines" ] && echo 0 || echo 1)"
else
  skip "RULE-05: root AGENTS.md @-imports" "AGENTS.md missing or is a symlink"
fi

# --- RULE-06: generated Codex paths are ignored ----------------------------
check "RULE-06: .gitignore ignores generated .codex/ and .agents/" \
  "$(grep -qE '^\.codex/$' .gitignore && grep -qE '^\.agents/$' .gitignore && echo 0 || echo 1)"

# --- RULE-07: Codex documentation host allowlist (repo-wide) ---------------
# Any URL whose host or path mentions codex must be on an OpenAI-operated host
# or the openai GitHub org. No exclusions: history is held to this too.
BAD_HOSTS="$(grep -rhoE 'https?://[A-Za-z0-9._-]+[^ )"]*codex[^ )"]*' \
  --exclude-dir=.git . 2>/dev/null |
  grep -vE '^https://(developers\.openai\.com|learn\.chatgpt\.com|github\.com/openai/)' |
  sort -u)"
if [ -n "$BAD_HOSTS" ]; then
  printf "%s\n" "$BAD_HOSTS" | sed 's/^/    /'
fi
check "RULE-07: every Codex URL is on an OpenAI-operated host" \
  "$([ -z "$BAD_HOSTS" ] && echo 0 || echo 1)"

# --- RULE-08: user-facing docs use https on allowlisted hosts --------------
INSECURE="$(grep -rhoE 'http://[A-Za-z0-9._-]+' README.md README.ja.md AGENTS.md 2>/dev/null |
  grep -vE '^http://(localhost|127\.0\.0\.1)' | sort -u)"
if [ -n "$INSECURE" ]; then
  printf "%s\n" "$INSECURE" | sed 's/^/    /'
fi
check "RULE-08: user-facing docs cite no non-HTTPS URL" \
  "$([ -z "$INSECURE" ] && echo 0 || echo 1)"

# RULE-09 (NFR-002, spec-021: the Codex-import migration must not weaken
# Claude Code) is retired. It guarded `.claude/hooks/` presence, then (after
# specs/025-remove-claude-hooks/) only `.permissions.deny`; that key no
# longer exists either (specs/026-remove-permissions-config/), so there is
# nothing left for this rule to check.

# --- RULE-10: install.sh no longer deploys Codex artifacts -----------------
if [ -f install.sh ]; then
  # Only executable lines count: the header comment deliberately states that
  # this installer does NOT touch ~/.codex or ~/.agents, and saying so must not
  # trip the check that proves it.
  codex_refs="$(grep -nE '\.codex|\.agents|CODEX_' install.sh 2>/dev/null | grep -vE '^[0-9]+:[[:space:]]*#')"
  [ -n "$codex_refs" ] && printf "%s\n" "$codex_refs" | sed 's/^/    /'
  check "RULE-10: install.sh contains no Codex/agents deployment logic" \
    "$([ -z "$codex_refs" ] && echo 0 || echo 1)"
else
  check "RULE-10: install.sh present" 1
fi

echo ""
echo "===================="
printf "Results: ${GREEN}%d passed${NC}, ${RED}%d failed${NC}, ${YELLOW}%d skipped${NC}\n" "$PASS" "$FAIL" "$SKIP"

if [ "$FAIL" -gt 0 ]; then
  printf "\nFailed:%b\n" "$FAIL_NAMES"
  exit 1
fi
